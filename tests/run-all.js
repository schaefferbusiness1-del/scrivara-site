const discovered = fs.readdirSync(__dirname)
  .filter(name => name.endsWith('.test.js'))
  .sort();
const duplicates = tests.filter((name, index) => tests.indexOf(name) !== index).sort();
const registered = [...new Set(tests)].sort();
